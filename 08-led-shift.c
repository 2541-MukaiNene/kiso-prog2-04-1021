// 【まずやること】
//   ・実行して、0番目→2番目の順にLEDが点灯し、最後に0番目が消えることを確認する
// 【やってみよう】
//   ① 点ける・消すビットの番号（0や2の部分）を変えて、表示がどう変わるか確かめる
//   ② 7番目のLEDを点ける行を追加する
//   ③ 発展：^ を使って、n番目のLEDを反転する処理を作ってみる
// ==================================================
#include <stdio.h>

void show(unsigned char leds){
    for (int i = 7; i >= 0; i--) {
        printf("%s", (leds & (1 << i)) ? "●" : "○");
    }
    printf("\n");
}

int main(void){
    unsigned char leds = 0;
    leds = leds | (1 << 0); /* 0番目を点ける */
    show(leds);
    leds = leds | (1 << 2); /* 2番目を点ける */
    show(leds);
    leds = leds & ~(1 << 0); /* 0番目を消す */
    show(leds);
    leds = leds | (1 << 7); /* 2番目を点ける */
    show(leds);
    return 0;
}
