// 【内容】平均点が整数の割り算で切り捨てられている。小数まで正しく表示されるように直す
// 【まずやること】
//   ・実行して、79 と表示される（本当の平均は79.6）ことを確認する
//   ・なぜ79と表示されるのか、sum と count の型に注目して確認する
// 【やってみよう】
//   ① 小数まで正しく表示されるように、printfの書式とキャストを直す
//   ② 直した後、scores の中身を変えても正しい平均が表示されるか確かめる
// ==================================================
#include <stdio.h>

int main(void)
{
    int scores[5] = {80, 75, 90, 65, 88};
    int sum = 0;
    int count = 5;
    int i;

    for (i = 0; i < count; i++) {
        sum += scores[i];
    }

    printf("%f\n", sum / (float)count);  /* ← 小数まで表示されるように、ここを直す */
    return 0;
}
