// 【内容】Ariane 5の事故を再現：64bitの小数を16bitの整数にキャストして範囲を超える
// 【まずやること】
//   ・実行する前に、speed16 の値を予想する
//   ・実行して、40000 -> -25536 と表示されることを確認する
// 【やってみよう】
//   ① speed の値を 32767 以下（例：30000）に変えて、範囲内なら正しく変換されることを確かめる
//   ② speed を 32768 に変えると、speed16 はいくつになるか予想してから確かめる
// ==================================================
// double→short を直接キャストすると、値が範囲外のとき規格上は未定義動作になるため、
// ここではdouble→int（収まる）→short（16bitの範囲を超える・実装依存）の2段階にしている
#include <stdio.h>

int main(void)
{
    double speed = 40000.0;
    int speed_int = (int)speed;
    short speed16 = (short)speed_int;

    printf("%d -> %d\n", speed_int, speed16);
    return 0;
}
