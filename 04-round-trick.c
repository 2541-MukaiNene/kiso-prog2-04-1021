// 【内容】(int)(x + 0.5) で四捨五入ができることを確かめ、負の数でも正しく動くように修正する
// 【まずやること】
//   ・実行して、x = 3.7 のとき (int)(x + 0.5) が 4 になることを確認する
//   ・x を -3.7 に変えて実行し、結果が -3 になってしまうことを確認する
//   ・なぜ -4 にならず -3 になるのか、計算過程をコメントで書いて確かめる
//     （ヒント：-3.7 + 0.5 = -3.2。(int)キャストは0方向への切り捨てなので、-3.2 は -3 になる）
// 【やってみよう】
//   ① 負の数でも正しく四捨五入（-3.7 なら -4）されるように、計算式を修正する
//      （ヒント：xが負のときは 0.5 を足すのではなく引く）
//   ② 修正した式が、正の数（3.7 など）でも正しく動くか確かめる
// ==================================================
#include <stdio.h>

int main(void)
{
    double x = -3.7;

    printf("%d\n", (int)(x >= 0 ? x + 0.5 : x - 0.5));  /* ← 負の数でも正しく四捨五入されるように、ここを書き換える */
    return 0;
}

//-3.7+0.5=-3.2。0方向への切り捨てのため-3になる
